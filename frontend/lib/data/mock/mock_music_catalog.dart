/// The demo music library. Every title and artist is fictional; the audio is a
/// generated preview, not a recording.
///
/// A few entries are **deliberately unusable** (expired licence, wrong
/// country, restricted) to show that the server's rights check removes them
/// from every list. In production the catalogue comes from licensed,
/// platform-owned or creator-owned sources and is never hand-listed.
MusicTrack _t(
  String id,
  String title,
  String artist,
  String language,
  String genre,
  int minutes,
  int seconds,
  MusicRightsType rights,
  List<MusicCategory> cats,
  int reels, {
  List<String> countries = const ['IN'],
  DateTime? expiry,
}) => MusicTrack(
  id: id,
  title: title,
  artist: artist,
  language: language,
  genre: genre,
  duration: Duration(minutes: minutes, seconds: seconds),
  rightsType: rights,
  categories: cats,
  reelsCount: reels,
  allowedCountries: countries,
  licenseExpiry: expiry,
  previewSeed: id.hashCode & 0xFFFF,
);

